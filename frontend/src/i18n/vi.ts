/**
 * F-Link Status: Disable Tamper chỉ che TMP → OK; Instant ACT vẫn hiện ACT.
 */
export function effectiveDeviceStatus(
  state: string | null | undefined,
  disable?: string | null,
): string {
  const st = (state || 'ok').toLowerCase()
  const bypass = (disable || 'none').toLowerCase()
  if (bypass === 'tamper' && st === 'tamper') return 'ok'
  return st
}

export function deviceDisableOf(disable?: string | null): 'none' | 'input' | 'device' | 'tamper' {
  const v = (disable || 'none').toLowerCase()
  return v === 'input' || v === 'device' || v === 'tamper' ? v : 'none'
}

